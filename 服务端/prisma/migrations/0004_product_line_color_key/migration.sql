-- 0004_product_line_color_key（2026-09-15）
--
-- 口径来源（★ 真相源）：
--   · 《销售CRM业务需求文档》V1.26 §13.3：「**产品线 = 全系统固定配色**（7 条线各一色）」
--     ⚠ 同段还要求「部门颜色在【部门管理】配置（每部门一个色值）」—— 经核 `department` 表**同样
--     没有色值列**，属**另一个缺口**（组织架构管理页 = M6/D5 时补），本条**只解决产品线侧**
--     （`product_line.color_key` 在 `/relations` 列表项里就直接要，属 M3/M4 眼前所需）。
--   · 《销售CRM接口API文档》V1.15 §4.1（`/org/product-lines` 返回 `color_key`）、
--     §5.3（产品线出参 `{id,name,code,color_key,dept_ids,service_cycle_days,status}`）、
--     §5.6（关系列表项 `product_line:{id,name,color_key}`）、§四（实体引用内嵌形状）。
--
-- ★ 这是**规格内部打架**的收口，不是"新需求"：
--   需求 ＋ 接口都要求该字段，而《数据架构文档》A7 的 `product_line` 表定义里没有它
--   （`migration 0001` 建表自然也没有），种子文件注释里其实早已把这条记成缺口。
--   ⇒ 三处口径对齐：**数据架构 A7 补该列（V1.30 → V1.31）**，接口 / 需求不动（它们本来就对）。
--
-- ★ 为什么可空（`NULL`）：存量行（当前 3 条 DEV 占位线）**不能瞎填默认色** ——
--   配色是业务决定（7 条线各一色，具体色值由七叔定）；给一个"假默认色"会让前端理直气壮地
--   渲染错颜色，而且没人会再回来改。未配置＝`NULL`，渲染回落与色值替换留待口径到位。
--   种子（`prisma/seed/001_dev_seed.sql`）已给出 3 条占位线的过渡色键。
-- =============================================================================

ALTER TABLE `product_line`
  ADD COLUMN `color_key` VARCHAR(32) NULL
    COMMENT '固定配色键（7 条线各一色，前端照渲染，→ 需求 §13.3）'
    AFTER `code`;
