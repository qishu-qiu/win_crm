-- =============================================================================
-- 0005_commitment_waive_reason（2026-09-15）
--
-- 口径来源（★ 真相源）：
--   · 《销售CRM业务需求文档》§10.1：「到期 → 进今日动线；逾期 → 次日置顶标红；
--     **豁免必须填原因**」；同节 them 类承诺出口：「客户答应我一直不兑现 → 催问 3 次无果 →
--     系统建议转卡点或判死。否则这类承诺只有**豁免（要填原因）**和无限拖延两条路」。
--   · 七叔 2026-09-15 拍板「取消 / 豁免」分界：
--       `cancelled`（取消）＝ **录错了 / 不成立了**（不需原因，纠正误录）；
--       `waived`（豁免）＝ **确有其事但做不成**（客户变卦、特殊原因做不了…）—— **必须留原因**。
--
-- ★ 这是「规格要求了、表里却没有落点」的补齐，不是"新需求"：
--   数据架构 D1 的 `status` 早已列出 `waived(豁免，必填原因)`，需求 §10.1 也要求必填原因，
--   但 `commitment` 表**没有任何存原因的列**（`daily_agenda.action_reason` 是**动线条目**的，
--   不是承诺的）⇒ D 域此前**不敢开放** `waived` 写入（收下原因无处可存 ＝ 假契约，→ 交接说明 §二 A）。
--   ⇒ 三处口径对齐：**数据架构 D1 补该列（V1.31 → V1.32）** ＋ 需求 §10.1 补分界（V1.26 → V1.27）。
--
-- ★ 为什么可空（`NULL`）：原因**只在 `waived` 时有值**——
--   `open`（进行中）/ `done`（兑现）/ `cancelled`（取消）三态**都不该有原因**。
--   给 `NOT NULL DEFAULT ''` 会让「没豁免的承诺」也顶着一条空原因，
--   将来统计「豁免原因 Top N」得先擦掉这批空串，属自找麻烦。
--   ⇒ 应用层约束：`status=waived` 时必填（422），其余状态一律为空。
--
-- ★ 性质：纯 `ALTER TABLE` 加列，**不回填数据、无破坏性**（存量行全为 NULL）。
--   表数不变（仍 46 张业务表），**无新增索引**（该列只随承诺行读出，不做检索维度）。
-- =============================================================================

ALTER TABLE `commitment`
  ADD COLUMN `waive_reason` VARCHAR(255) NULL
    COMMENT '豁免原因（status=waived 必填；cancelled 取消不需原因，→ 需求 §10.1）'
    AFTER `status`;
