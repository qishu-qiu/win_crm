-- 0009_employee_preferences（2026-09-18）
--
-- 口径来源（★ 真相源）：
--   · 《销售CRM设计规范》§八.1：「主题切换＝换 token 变量值（入口在页 28，**存账号**）」
--     ＋ 接口 §4.14.9 `PUT /account/preferences`（**存账号**）—— 但《数据架构文档》一直
--     **没有 theme 的落点** ⇒ 主题此前只能存浏览器本机（`localStorage['crm_theme']`）。
--   · 《销售CRM业务需求文档》§13.4「全局框架规范」：侧栏「**折叠状态按账号持久化**」
--     —— 同样无落点，此前只能存本机（`localStorage['crm_nav_open']`）。
--   · 《销售CRM前端页面与交互文档》§四.1：个人中心 / 外观设置收在**顶部头像菜单** → `/me/appearance`。
--   ⇒ 2026-09-18 七叔拍板（→《欠账登记表》D-37 / D-36⑥ / D-41）：**偏好落 `employee` 两列**。
--
-- 为什么是「employee 加列」而不是「单开一张偏好表」：
--   · 偏好是**员工 1:1 的小配置**（一个主题码 ＋ 一组分组键）——单开表＝为两个字段建一张
--     1:1 表，每次取「我是谁」都要多一次 JOIN，收益为负；
--   · 与 A2 已有的 `extra_dept_ids` / `product_line_ids` 同风格：**结构化小配置走 JSON 列**
--     （→ `prisma/README.md` §七「JSON 列」条）。
--
-- 为什么 `theme` 可空（而不是 `NOT NULL DEFAULT 'light'`）：
--   「**从未设置过**」与「**显式选了白天**」是两件事 —— 前者应跟随默认值（设计规范 §八.1
--   「公司只锁默认值（light）」），后者是用户的明确选择。给默认值会让两者都变成 'light'，
--   将来若默认值改成别的（或按部门配默认），存量行会被错误地当成"用户选过 light"。
--
-- 为什么 `nav_open` 不给 `DEFAULT '[]'` 同款理由：空数组 = 「没存过 / 全收起」，给默认值
--   会让「首次进站」与「用户手动全收起」不可区分（前者应展开当前分组、后者应尊重用户）。
--
-- ⚠ `0001_init` 是**冻结基线**（已 `resolve --applied`），改动它会与 `_prisma_migrations`
--   的校验和不一致 ⇒ 一律走**新增量**（口径见 `服务端/prisma/README.md §六` / `CODEBUDDY.md §5`）。
--
-- 性质：**新增两个可空列**，不动数据、不动约束、**无新增索引**
--   （两列都只按主键读 / 写，没有任何「按 theme 筛人」的用法，故不建索引）。
-- =============================================================================

ALTER TABLE `employee`
  ADD COLUMN `theme` VARCHAR(16) NULL
    COMMENT '个人主题（light 白天 / dark 夜间）；NULL = 从未设置，前端回落默认值 ★ 2026-09-18 migration 0009',
  ADD COLUMN `nav_open` JSON NULL
    COMMENT '侧栏展开分组键（JSON 数组，→ 需求 §13.4「折叠状态按账号持久化」）；NULL = 从未设置 ★ 2026-09-18 migration 0009';
