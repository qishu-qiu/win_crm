/** 脱敏档位（→ 数据架构 §十一 `level` 语义：`visible` ＝ 原文、`masked` ＝ 打码） */
export type DesensitizeLevel = 'visible' | 'masked';

/** 金额打码形态（→ 数据架构 §十一 ③：`amount_masked: "***"` —— **不显示数字**，不是「遮几位」） */
export const AMOUNT_MASK = '***';

/** `resolveDeptDesensitize` 的入参（**具名**：调用点不许出现裸 `true`，免得读不出在传什么） */
export interface DeptDesensitizeInput {
  /**
   * 登录人「**本人所属 ∪ 管辖 ∪ 兼职**」的部门集合
   * ＝ `RequestContext.deptIds`（`dept` 档＝管辖部门；其余档＝本人所属/兼职）。
   * ⚠ 不要用 `DataScopeTarget` 推：那是「看得到谁」，与「金额算不算跨部门」不是同一件事。
   */
  readonly viewerDeptIds: readonly bigint[];
  /** 被看对象**归属的部门**（当前唯一预期的消费者＝ C1 `business_relation.dept_id`） */
  readonly targetDeptId: bigint;
  /**
   * 我是不是**总经理**（→ 需求 §4.3 四 末行「总经理 ＝ 真实金额」；2026-09-15 七叔：
   * 「总经理可查看全部」）。**管理员必须传 `false`**（不解除金额脱敏，→ §2.2）。
   */
  readonly isGeneralManager: boolean;
}

/**
 * 「跨业务线」脱敏判定 —— **按部门**比 ＋ **总经理例外**（→ 需求 §4.3 四；2026-09-15 七叔口径）。
 *
 * @returns `'visible'`（给真实金额）＝ 总经理 **或** 该对象归属部门 ∈ 我的部门集合；
 *          `'masked'`（给 `amount: null` ＋ `amount_masked: "***"`）＝ 其余
 *
 * ★ 空集合 → **`'masked'`**：没有部门可比 ＝「哪里都不属于」，**不默认放行**
 *   （与 `data-scope-target.ts`「未知档位一律落最窄」同一条思路：宁可少给，不可默认全量）。
 */
export function resolveDeptDesensitize(input: DeptDesensitizeInput): DesensitizeLevel {
  if (input.isGeneralManager) return 'visible';
  return input.viewerDeptIds.includes(input.targetDeptId) ? 'visible' : 'masked';
}
