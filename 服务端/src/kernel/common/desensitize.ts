// 脱敏判定（M5-05）—— ★ 「跨业务线要不要脱敏」的**唯一判定点** ★
//
// 口径来源（★ 真相源，勿自造）：
//   · 《销售CRM业务需求文档》§4.3 四「金额脱敏（跨部门）」：
//     真实金额 ＝ 归属本人 / 协同人、部门经理·**管辖内**、总经理；
//     完全脱敏 ＝ 部门经理·**跨管辖** / 销售 / 客服 / 交付 / **管理员**（管理员「不解除金额脱敏」）。
//     ★ **判断口径 ＝ 按部门**（2026-09-10 定）：看这条业务关系**归属的部门**与登录人
//       （所属 / 管辖）部门是否一致，**不一致 → 完全脱敏**；**明令不按产品线判断**
//       （一人可挂多条产品线，按产品线判会自相矛盾）。
//   · 《销售CRM数据架构文档》§十一 ③：出参形态 ＝ **`amount: null` ＋ `amount_masked: "***"`**。
//   · 《销售CRM架构设计说明》§7.3：**规则写在一处，改口径只改这一处**。
//   · 同 §4.3 四 ★ / §7.3：**报表 / 看板 / 汇总不脱敏**（经理 / 老板出口）—— 那是**出口豁免开关**
//     的事，落点在 `kernel/context/desensitize-exempt.decorator.ts`，**不在本文件**。
//
// ★ 为什么落点是 `kernel/`（三条理由同 `data-scope/data-scope-target.ts`）：
//   ① `shared/**` 业务域**不许 import**（§5.4 硬卡）⇒ 放 shared 等于各域都用不到；
//   ② `modules/<域>/domain/**` 是**本域私有**，别的域引它就是跨域引内部实现（§5.3 禁止）；
//   ③ `kernel/**` 是唯一「**所有域都能用** ＋ 与被依赖方无环」的位置，且天然是纯函数、零框架依赖。
//
// ★ 本文件**只做「按部门 ＋ 总经理例外」这两维**（2026-09-15 七叔口径，原话：
//   「**本部门都可查看，其他部门不可查看；总经理可查看全部**」——销售可看自己部门的金额，
//   其他部门的看不了）。**明确不做的两件事**：
//   ① **管理员不算例外**：管理员「**不解除金额脱敏**」（→ 需求 §2.2 / 接口 §2.2）⇒ 调用方
//      **不许**把管理员当总经理传 `isGeneralManager: true`；
//   ② ⚠ **待确认一格**（已登记 → 交接说明 §二）：需求 §4.3 四 表首行写「**归属本人 / 协同人**
//      ＝ 真实金额」，而「协同人」**正式协同可跨部门** —— 跨部门协同人按本函数（按部门）会拿到 `masked`。
//      七叔 2026-09-15 的口径是「按部门」这一句，未点协同人；故**先按按部门实现并书面登记**，
//      不擅自把那一格改掉（→ 坑 24：**契约冲突只报不改**）。
//   「归属本人」不受影响：他的关系必然落在自己的部门集合里（含兼职部门）。
//
// ⚠ 本批**没有消费者**（合同 / 回款 ＝ E 域尚未建，C 域列表也还没出金额）⇒ 入参形状是**按上述
//   口径定的**，不是按某个调用方猜的；第一个消费者出现时直接用，**别在调用方另写一套**。
//
// 分层约束（架构 §5.4）：本文件**不 import `@nestjs/*` / `@prisma/client`、不查库**。
