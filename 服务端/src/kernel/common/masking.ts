// 口径来源（★ 真相源，勿自造）：
//   · 《销售CRM数据架构文档》V1.32 §十一「联系方式」：
//     **列表 / 卡片**出参给 `phone_masked`（**`xxx****xxxx`**）—— ★ 明确写着这是**出参形态**、
//     **不是权限**（"能看 / 能锁"的业务规则在需求 §4.3，不在这里）。
//   · 《销售CRM接口API文档》V1.18 §5.5：`ContactBrief`「列表 / 卡片出参一律 `phone_masked`」；
//     同 §5.4：查重候选出参带 `credit_code_masked`。
//   · 同 §2.8：**详情**给全号、被 owner 上锁时才不给号 —— 故本文件**只负责打码**，
//     「什么时候打码」（详情 / 列表 / 锁）由各出口决定（M5 统一到拦截器）。
//
// ⚠ 信用代码的脱敏形态**规格未给**（只给了字段名 `credit_code_masked`）：
//   此处按「前 4 ＋ `****` ＋ 后 4」实现（保留足够的肉眼辨识度：前 4 含登记管理部门与机构类别码），
//   **属技术口径，待规格补齐**；要改只动本函数。
//
// 分层约束（架构 §5.4）：kernel 零业务 —— 本文件只做**字符串形态变换**，不查库、不判权限。
