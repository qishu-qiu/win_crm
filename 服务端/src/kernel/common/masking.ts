/** 打码占位（统一用 4 个星号，与 §十一 的 `xxx****xxxx` 一致；不随原文长度变化，免得泄露位数） */
const MASK = '****';

/**
 * 手机号 / 电话 → 打码形态（`138****0000`）。
 *
 * 规则：**前 3 ＋ `****` ＋ 后 4**（→ §十一）。
 * · 长度不足（`<= 7`）时无法保留前后段 → **整体打码**（宁可看不出，也不露出短号的绝大部分）；
 * · 传空串原样返回（空值不是"要打码的东西"，交给上层的空值口径）。
 */
export function maskPhone(phone: string): string {
  const text = String(phone).trim();
  if (text === '') return '';
  if (text.length <= 7) return MASK;

  return `${text.slice(0, 3)}${MASK}${text.slice(-4)}`;
}

/**
 * 统一社会信用代码 → 打码形态（`9134****1234`）。
 * ⚠ 形态**规格未给**（→ 文件头），当前＝前 4 ＋ `****` ＋ 后 4；改口径只动这里。
 */
export function maskCreditCode(creditCode: string): string {
  const text = String(creditCode).trim();
  if (text === '') return '';
  if (text.length <= 8) return MASK;

  return `${text.slice(0, 4)}${MASK}${text.slice(-4)}`;
}
