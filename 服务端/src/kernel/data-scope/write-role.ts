// 口径来源（★ 真相源，勿自造）：
//   · 《销售CRM业务需求文档》§4.2 可见范围表 ＋ ★ 管理员护栏：
//       **管理员**「可查看业务数据，但**一律只读**、不参与客户经营」；
//       同节 ★ **交付 / 客服**「只读；不进公海、不做客户经营动作」。
//   · 《销售CRM架构设计说明》§7.2 四档：`all`（总经理 / 管理员）/ `dept`（经理）/
//       `self`（销售）/ `serving`（交付·客服）—— ⚠ **档位只表达"能看到谁"**，
//       只读与否**不塞进档位值**（§7.2 尾注），故「能不能写」必须是**独立判定**，就是本文件。
//   · ⇒ 可写集合 ＝ `sale` / `dept_manager` / `gm`；`admin` / `delivery` / `service` 只读。
//   · ★ **多角色叠加取"能写"**：`admin` ＋ `sale` 的人**仍可写** —— 与 `resolveDataScope`
//     「多角色取更宽」同一条思路，**不是**「有一个只读角色就全禁」（2026-09-15 定）。
//
// ⚠ **适用范围（别拿它当"万能写权限"）**：本函数判的是「**客户经营类**写动作」
//   —— 建档 / 改关系 / 加成员 / 写跟单 / 写承诺。
//   **不在范围**：① **台账编辑**（需求 §7.7 明文「**交付/客服可编辑**」，属"交付物"不是客户经营）
//     ② 组织 / 字典 / 规则维护（那是 `admin` 的本职，走 A 域权限）
//     ③ 管理员点名的例外写动作（如 §7.9「无直属经理时**兜底发起**离职批量转交」）。
//   这三类由各自域 / 各自端点判定，**不许套本函数**（套了就是把交付 / 客服的正当写权一起掐掉）。
//
// ★ 为什么落在 `kernel/`（同一批 `data-scope-target.ts` 的理由）：
