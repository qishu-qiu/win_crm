/**
 * 可写「客户经营类」业务数据的角色码（＝ `role.code`）。
 * ⚠ 顺序＝**权限从大到小**（与 `org/domain/data-scope.ts` 的排序同源）；改这里＝改全局写权限，先拿令。
 */
export const BUSINESS_WRITE_ROLES = ['sale', 'dept_manager', 'gm'] as const;

/**
 * 该角色集合能否写**客户经营类**业务数据。
 *
 * ★ 判据＝**至少持有一个可写角色**（多角色取"能写"，见文件头 ★）。
 *   纯只读角色（`admin` / `delivery` / `service`）→ `false`（调用方给 **403 / 20003**）。
 * ⚠ 适用范围见文件头 ⚠ 段（台账 / 组织维护 / 管理员点名例外**不走本函数**）。
 */
export function isBusinessWriteRole(roleCodes: readonly string[]): boolean {
  return BUSINESS_WRITE_ROLES.some((code) => roleCodes.includes(code));
}
