/**
 * 一个字段算不算「已填」（→ E8「非空即过」）。
 *
 * ★ 为什么把 `trim()` 算进去：数据库里 `'   '` 是"填了但等于没填"——
 *   若按 `!== null` 判定，销售在档案里敲了一串空格就能绕过签约必填校验，
 *   换成"合同签了才发现公司档案是空的"。口径按**人填没填**判，不按存储值判。
 * ★ `undefined` 与 `null` 同义：口径只关心"没有内容"，不关心"没传"还是"存的是 NULL"。
 */
export function isFieldFilled(value: string | null | undefined): boolean {
  return typeof value === 'string' && value.trim() !== '';
}