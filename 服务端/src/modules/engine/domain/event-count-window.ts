/** 计数窗的自然日数（30）—— 「近 30 天」的那个 30 */
export const EVENT_COUNT_WINDOW_DAYS = 30;

const MS_PER_DAY = 24 * 60 * 60 * 1000;

/**
 * 计数窗的**起点时刻**（含）：`[起点, 现在]` 即「近 30 个自然日（含今天）」。
 *
 * ★ 为什么是 `days - 1`：窗是**按自然日数**数的 —— 今天算第 1 个自然日，往前数满 30 个
 *   （今天、昨天、…、29 天前）。若写 `days`，窗口实际覆盖 31 个自然日，与「近 30 天」不符。
 * ★ 日界取 **UTC**（见文件头）；返回的是 `Date`（绝对时刻），落库 / 比较都是它。
 */
export function resolveEventCountSince(
  now: Date,
  days: number = EVENT_COUNT_WINDOW_DAYS,
): Date {
  const todayUtcMidnight = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  return new Date(todayUtcMidnight - (days - 1) * MS_PER_DAY);
}
