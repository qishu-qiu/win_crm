// =============================================================================
// 脱敏拦截器（M0-37）—— ★★ 本批次**只做占位**，真实脱敏在 M5 ★★
//
// 口径来源（★ 真相源，勿自造）：
//   · 《销售CRM架构设计说明》V1.1 §7.3 脱敏渲染：**出口统一处理**；
//     ★「报表 / 看板 / 汇总出口**不脱敏**（经理、老板看真实金额）；
//        脱敏只作用于**销售看他人私海 / 跨部门关系**」。
//   · 《销售CRM业务需求文档》§8 / 数据架构文档 §十一：手机号等字段的展示口径。
//
// ★ 为什么现在不实现（诚实登记技术债）：
//   「脱敏」不是「把所有手机号打码」——它取决于**看一眼数据的人是谁 × 数据是谁的**：
//     销售看自己的私海要**明文**，看他人私海才脱敏；经理看下属的、看报表要**明文**。
//   也就是说，脱敏规则必须同时读「上下文（我是谁）」＋「这条记录属于谁」＋「这个出口要不要脱敏」，
//   而这三样东西分别落在 M5（数据范围）与各域的真实 DTO 上 —— 此刻一条真数据都没有，
//   先写出来的规则**必错**（而且错的方向是「把经理该看的真金额打码了」，属于业务事故级错误）。
//   故本占位**刻意不猜任何规则**，只做两件不会返工的事：
//     ① 把「本出口是否脱敏」这个开关**留在一个位置上**（`isDesensitizeExempt`），M5 往这里挂；
//     ② 立下约束：脱敏**永远不在 repository / domain 改数据**，只在出口（本层）渲染 —— 否则
//        一旦落库或缓存被写脏，恢复不了。
//
// ★ 两条硬约束：
//   ① 本文件**永不注入 Prisma / repository**（§7.1 横切层不查库）；
//   ② 判断「记录属于谁」**不许查库**——需要归属信息时，由业务侧在查询阶段一并带出（M5 设计点）。
// =============================================================================
import { type CallHandler, type ExecutionContext, Injectable, type NestInterceptor } from '@nestjs/common';
import { type Observable } from 'rxjs';

/**
 * 出口豁免脱敏的容器标记键（M5 往这里挂）。
 * 用法（M5 起）：报表 / 看板 / 汇总类 controller 标 `@DesensitizeExempt()`，
 * 拦截器读到豁免标记就**原样放行**（→ §7.3「报表/看板/汇总出口不脱敏」）。
 */
export const DESENSITIZE_EXEMPT_KEY = 'desensitize:exempt';

@Injectable()
export class DesensitizeInterceptor implements NestInterceptor {
  intercept(_executionContext: ExecutionContext, next: CallHandler): Observable<unknown> {
    // ★ M0 占位：不读上下文、不改数据、直接放行。
    //   之所以连「读上下文」都不做：读了却没有规则可用，等于制造「看起来在工作」的假象
    //   —— 本项目的规矩是**占位就明说占位**（M5 会把这个方法体填成真实规则）。
    return next.handle();
  }
}
